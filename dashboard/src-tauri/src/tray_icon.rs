//! The tray icon's pure rasteriser (DESIGN 9.11). T15 writes the body.

use jev_usage_core::assess::Severity;

/// What the icon shows: a ring gauge in 5 % steps and the level's shape.
#[derive(Copy, Clone, Eq, PartialEq, Debug)]
pub struct IconSpec {
    /// The usage in 5 % steps, 0..=20.
    pub used_step: u8,
    /// The level, drawn as a shape and not only a colour.
    pub level: Severity,
}

const OUTLINE: [u8; 4] = [128, 128, 128, 255];
const INK: [u8; 4] = [38, 38, 42, 255];

/// The icon as RGBA bytes, `size * size * 4` long; integer arithmetic only.
pub fn render(spec: IconSpec, size: u32) -> Vec<u8> {
    let n = usize::try_from(size).unwrap_or(64);
    let mut buf = vec![0_u8; n.saturating_mul(n).saturating_mul(4)];

    let c = i64::try_from(n).unwrap_or(64) / 2;
    let r_outer = c.saturating_sub(1);
    let thickness = (i64::try_from(n).unwrap_or(64) / 8).max(2);
    let r_inner = r_outer.saturating_sub(thickness);

    let (cos_tab, sin_tab) = circle_table();
    let fill_deg = u32::from(spec.used_step).saturating_mul(18).min(360);
    let dashed = matches!(spec.level, Severity::Unknown);

    for a in 0..360_u16 {
        let idx = usize::from(a);
        let cos = cos_tab.get(idx).copied().unwrap_or(65_536);
        let sin = sin_tab.get(idx).copied().unwrap_or(0);
        let color = if dashed {
            if (usize::from(a) / 30).is_multiple_of(2) {
                Some(OUTLINE)
            } else {
                None
            }
        } else if in_fill(a, fill_deg) {
            Some(INK)
        } else {
            Some(OUTLINE)
        };
        if let Some(color) = color {
            for d in r_inner..=r_outer {
                let px = c.saturating_add(d.saturating_mul(cos) / 65_536);
                let py = c.saturating_add(d.saturating_mul(sin) / 65_536);
                set_pixel(&mut buf, n, px, py, &color);
            }
        }
    }

    if !dashed {
        match spec.level {
            Severity::Warn => fill_disc(&mut buf, n, c, thickness / 2, &INK),
            Severity::Critical => fill_disc(&mut buf, n, c, r_inner.max(1), &INK),
            _ => {}
        }
    }

    buf
}

/// True when `a` (degrees, 0 at right, clockwise) is inside the fill arc from the top.
fn in_fill(a: u16, fill_deg: u32) -> bool {
    let a = u32::from(a);
    let start = 270_u32;
    let end = start.saturating_add(fill_deg);
    if end <= 360 {
        a >= start && a < end
    } else {
        a >= start || a < end.saturating_sub(360)
    }
}

fn fill_disc(buf: &mut [u8], n: usize, c: i64, r: i64, color: &[u8; 4]) {
    let mut dy = 0_i64.saturating_sub(r);
    while dy <= r {
        let mut dx = 0_i64.saturating_sub(r);
        while dx <= r {
            let d2 = dx.saturating_mul(dx).saturating_add(dy.saturating_mul(dy));
            if d2 <= r.saturating_mul(r) {
                set_pixel(buf, n, c.saturating_add(dx), c.saturating_add(dy), color);
            }
            dx = dx.saturating_add(1);
        }
        dy = dy.saturating_add(1);
    }
}

fn set_pixel(buf: &mut [u8], n: usize, x: i64, y: i64, color: &[u8; 4]) {
    if x < 0 || y < 0 {
        return;
    }
    let x = usize::try_from(x).unwrap_or(n);
    let y = usize::try_from(y).unwrap_or(n);
    if x >= n || y >= n {
        return;
    }
    let i = y.saturating_mul(n).saturating_add(x).saturating_mul(4);
    if let Some(px) = buf.get_mut(i..i.saturating_add(4)) {
        px.copy_from_slice(color);
    }
}

/// 360 (cos, sin) pairs, fixed-point with scale 2^16, generated by integer rotation.
fn circle_table() -> (Vec<i64>, Vec<i64>) {
    const COS1: i64 = 65_526;
    const SIN1: i64 = 1_144;
    let mut cos = vec![0_i64; 360];
    let mut sin = vec![0_i64; 360];
    let mut c = 65_536_i64;
    let mut s = 0_i64;
    for i in 0..360 {
        if let Some(e) = cos.get_mut(i) {
            *e = c;
        }
        if let Some(e) = sin.get_mut(i) {
            *e = s;
        }
        let nc = c.saturating_mul(COS1).saturating_sub(s.saturating_mul(SIN1)) / 65_536;
        let ns = c.saturating_mul(SIN1).saturating_add(s.saturating_mul(COS1)) / 65_536;
        c = nc;
        s = ns;
    }
    (cos, sin)
}
